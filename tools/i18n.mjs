// Compile the message dictionaries into the client bundle and the locale files.
//
// The bundle cannot read files at runtime, so the strings have to be inlined;
// keeping the source here and generating both copies is what stops the panel
// from showing one language while Plugin Manager shows another.
//
//   node tools/i18n.mjs            # report what would change
//   node tools/i18n.mjs --write    # stamp lib/client.js + locale/*.json
//
// After changing a string: edit tools/i18n-strings.mjs, then run with --write
// and `npm test` (the suite asserts the three copies agree).
import { readFileSync, writeFileSync } from "node:fs";
import { STRINGS } from "./i18n-strings.mjs";

const CLIENT = new URL("../lib/client.js", import.meta.url);
const LOCALES = ["zh", "en"];

const source = readFileSync(CLIENT, "utf8");

/** Byte range of `const NAME = { ... };`, brace- and string-aware. */
function sliceRange(text, name) {
  const marker = `const ${name} = `;
  const at = text.indexOf(marker);
  if (at < 0) throw new Error(`${name} not found`);
  let depth = 0;
  let quote = null;
  for (let i = at + marker.length - 1; i < text.length; i += 1) {
    const ch = text[i];
    if (quote) {
      if (ch === "\\") i += 1;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === "`") {
      quote = ch;
      continue;
    }
    if (ch === "{") depth += 1;
    else if (ch === "}") {
      depth -= 1;
      if (depth === 0) {
        const end = text[i + 1] === ";" ? i + 2 : i + 1;
        return { start: text.lastIndexOf("\n", at) + 1, end };
      }
    }
  }
  throw new Error(`${name} is not balanced`);
}

const problems = [];
const HAN = /[\u4e00-\u9fff]/;
for (const [key, pair] of Object.entries(STRINGS)) {
  if (!Array.isArray(pair) || pair.length !== 2) {
    problems.push(`${key}: expected [zh, en]`);
    continue;
  }
  const [zh, en] = pair;
  if (typeof zh !== "string" || zh === "") problems.push(`${key}: empty Chinese`);
  if (typeof en !== "string" || en === "") problems.push(`${key}: empty English`);
  if (HAN.test(en)) problems.push(`${key}: English still contains Chinese`);
  const zhSlots = [...String(zh).matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(",");
  const enSlots = [...String(en).matchAll(/\{(\w+)\}/g)].map((m) => m[1]).sort().join(",");
  if (zhSlots !== enSlots) problems.push(`${key}: placeholders differ (zh: ${zhSlots} / en: ${enSlots})`);
}

const meta = {
  zh: {
    title: "Codex Micro",
    description:
      "驱动 Work Louder Codex Micro 宏键盘：六个智能体键、旋钮、摇杆与逐键灯效，绑定到当前 Harness 会话。",
  },
  en: {
    title: "Codex Micro",
    description:
      "Drives a Work Louder Codex Micro macro-pad: six agent keys, encoder, joystick and per-key lighting, bound to this Harness session.",
  },
};

const dicts = {
  zh: Object.fromEntries(Object.entries(STRINGS).map(([key, pair]) => [key, pair[0]])),
  en: Object.fromEntries(Object.entries(STRINGS).map(([key, pair]) => [key, pair[1]])),
};

if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const problem of problems.slice(0, 40)) console.error("  " + problem);
  process.exit(1);
}

console.log(`${Object.keys(STRINGS).length} keys x ${LOCALES.length} locales`);

if (!process.argv.includes("--write")) {
  console.log("dry run — pass --write to stamp lib/client.js and locale/*.json");
  process.exit(0);
}

const render = (dict) =>
  Object.entries(dict)
    .map(([key, value]) => `\t\t\t\t${JSON.stringify(key)}: ${JSON.stringify(value)},`)
    .join("\n");

const block = `\t\t/**
\t\t * Message dictionaries, compiled in.
\t\t *
\t\t * Flat keys, one object per locale: that is exactly the shape the Host
\t\t * locale service looks up (it indexes the dictionary by key, it does not
\t\t * walk a path). The Chinese half doubles as the fallback when the service
\t\t * is absent, so a panel without locale support still reads as prose rather
\t\t * than as a wall of keys.
\t\t *
\t\t * Generated by tools/i18n.mjs from tools/i18n-strings.mjs. locale/{zh,en}.json
\t\t * carry the same strings for Plugin Manager, which reads meta.title and
\t\t * meta.description from disk.
\t\t */
\t\tconst LOCALE = {
\t\t\tzh: {
${render(dicts.zh)}
\t\t\t},
\t\t\ten: {
${render(dicts.en)}
\t\t\t},
\t\t};`;

const range = sliceRange(source, "LOCALE");
writeFileSync(CLIENT, source.slice(0, range.start) + block + source.slice(range.end), { encoding: "utf8" });

for (const locale of LOCALES) {
  const payload = { meta: meta[locale], ...dicts[locale] };
  writeFileSync(new URL(`../locale/${locale}.json`, import.meta.url), JSON.stringify(payload, null, 2) + "\n", {
    encoding: "utf8",
  });
}

console.log("stamped lib/client.js + locale/zh.json + locale/en.json");
